//! `remit pull`: fetch + verify a catalog and generate the LLM's compact API
//! reference: `.d.ts` types plus DDL, stats and examples.

use std::path::Path;

use anyhow::{anyhow, Context as _};
use base64::{engine::general_purpose::STANDARD, Engine as _};
use serde_json::Value;

pub async fn pull(holder: &str, name: Option<String>, dir: &Path) -> anyhow::Result<()> {
    let url = holder.trim_end_matches('/');
    let url = if url.starts_with("http") {
        url.to_string()
    } else {
        format!("https://{url}")
    };
    let resp = reqwest::get(format!("{url}/.well-known/remit"))
        .await
        .context("fetch catalog")?;
    let sig = resp
        .headers()
        .get("remit-signature")
        .and_then(|v| v.to_str().ok())
        .map(String::from);
    let catalog: Value = resp.json().await?;
    verify_catalog(&catalog, sig.as_deref())?;
    let name = name.unwrap_or_else(|| {
        catalog["holder"]
            .as_str()
            .unwrap_or("holder")
            .rsplit(':')
            .next()
            .unwrap_or("holder")
            .split('.')
            .next()
            .unwrap_or("holder")
            .to_string()
    });
    let out = dir.join(&name);
    std::fs::create_dir_all(out.join("examples"))?;
    std::fs::write(
        out.join("catalog.json"),
        serde_json::to_string_pretty(&catalog)?,
    )?;
    std::fs::write(out.join("types.d.ts"), types_dts(&catalog))?;
    std::fs::write(out.join("schema.sql"), schema_sql(&catalog))?;
    std::fs::write(
        out.join("stats.json"),
        serde_json::to_string_pretty(&catalog["stats"])?,
    )?;
    if let Some(ex) = catalog["examples"].as_array() {
        for (i, e) in ex.iter().enumerate() {
            let slug: String = e["title"]
                .as_str()
                .unwrap_or("example")
                .chars()
                .map(|c| {
                    if c.is_ascii_alphanumeric() {
                        c.to_ascii_lowercase()
                    } else {
                        '-'
                    }
                })
                .collect();
            std::fs::write(
                out.join("examples").join(format!("{i:02}-{slug}.json")),
                serde_json::to_string_pretty(&e["manifest"])?,
            )?;
        }
    }
    eprintln!(
        "pulled {} ({}) into {}",
        catalog["holder"].as_str().unwrap_or("?"),
        catalog["catalog_sha256"].as_str().unwrap_or("?"),
        out.display()
    );
    Ok(())
}

/// Verify the detached catalog signature against the key the catalog names.
/// (Senders that pin the Holder key should compare `keys[0].did_key` too.)
pub fn verify_catalog(catalog: &Value, sig_header: Option<&str>) -> anyhow::Result<()> {
    let h = sig_header.ok_or_else(|| anyhow!("catalog is not signed (missing Remit-Signature)"))?;
    let field = |k: &str| {
        h.split(',')
            .map(str::trim)
            .find_map(|p| p.strip_prefix(&format!("{k}=\"")))
            .map(|v| v.trim_end_matches('"').to_string())
    };
    let sig = STANDARD.decode(field("sig").ok_or_else(|| anyhow!("bad signature header"))?)?;
    let dk = catalog["keys"][0]["did_key"]
        .as_str()
        .ok_or_else(|| anyhow!("catalog has no keys"))?;
    let pk = remit_wire::public_key_from_did_key(dk).ok_or_else(|| anyhow!("bad holder key"))?;
    let body = remit_wire::jcs::canonical_bytes(catalog)?;
    if !remit_wire::identity::verify(
        &pk,
        &remit_wire::dsse::pae(remit_wire::CATALOG_TYPE, &body),
        &sig,
    ) {
        return Err(anyhow!("catalog signature does not verify"));
    }
    Ok(())
}

fn ts_type(t: &str) -> &'static str {
    match t {
        "bool" => "boolean",
        "int" | "float" => "number",
        "timestamp" | "date" => "Date",
        _ => "string",
    }
}

fn ident(s: &str) -> String {
    s.chars()
        .map(|c| if c.is_ascii_alphanumeric() { c } else { '_' })
        .collect()
}

pub fn types_dts(c: &Value) -> String {
    let mut s = format!(
        "// Generated by `remit pull` from {} ({}). Do not edit.\n// Kernels: `export default function main(reads: Reads, params: Params): Result`.\n\n",
        c["holder"].as_str().unwrap_or("?"),
        c["catalog_sha256"].as_str().unwrap_or("?")
    );
    s.push_str(
        r#"/** Lazy, Arrow-backed table returned by a declared read. */
export interface Table<Row> extends Iterable<Row> {
  readonly length: number;
  readonly schema: ReadonlyArray<{ name: string; type: string }>;
  /** Materialize rows (timestamps become Date). */
  rows(): Row[];
  /** Column as a typed array (numbers / epoch-ms timestamps) or plain array. */
  col<K extends keyof Row & string>(name: K): Row[K] extends number | Date | null ? Float64Array : Array<Row[K]>;
  map<U>(f: (r: Row, i: number) => U): U[];
  filter(f: (r: Row, i: number) => boolean): Row[];
  reduce<U>(f: (acc: U, r: Row, i: number) => U, init: U): U;
  forEach(f: (r: Row, i: number) => void): void;
  some(f: (r: Row) => boolean): boolean;
  every(f: (r: Row) => boolean): boolean;
  find(f: (r: Row) => boolean): Row | undefined;
  slice(a?: number, b?: number): Row[];
  at(i: number): Row | undefined;
}
/** A declared read template: call with its typed params (max_calls applies). */
export type Read<Row, P = Record<string, unknown>> = (params?: P) => Table<Row>;

"#,
    );
    let mut names = Vec::new();
    for r in c["resources"].as_array().into_iter().flatten() {
        let name = r["name"].as_str().unwrap_or("");
        names.push(name.to_string());
        if let Some(h) = r["hints"].as_object() {
            s.push_str(&format!(
                "/** `{name}` — {} */\n",
                serde_json::to_string(h).unwrap_or_default()
            ));
        }
        s.push_str(&format!("export interface {} {{\n", ident(name)));
        for col in r["columns"].as_array().into_iter().flatten() {
            let n = col["name"].as_str().unwrap_or("");
            let t = match col["enum"].as_array() {
                Some(vals) if !vals.is_empty() => vals
                    .iter()
                    .map(|v| v.to_string())
                    .collect::<Vec<_>>()
                    .join(" | "),
                _ => ts_type(col["type"].as_str().unwrap_or("string")).to_string(),
            };
            let null = if col["nullable"] == Value::Bool(true) {
                " | null"
            } else {
                ""
            };
            s.push_str(&format!("  {n}: {t}{null};\n"));
        }
        s.push_str("}\n\n");
    }
    s.push_str("export interface Resources {\n");
    for n in &names {
        s.push_str(&format!("  {:?}: {};\n", n, ident(n)));
    }
    s.push_str("}\n");
    s
}

pub fn schema_sql(c: &Value) -> String {
    let mut s = format!("-- Remit SQL reference for {} (visible catalog only).\n-- Time comes from params ($from, $until); now()/random() are not available.\n\n", c["holder"].as_str().unwrap_or("?"));
    for (i, r) in c["resources"].as_array().into_iter().flatten().enumerate() {
        if let Some(h) = c["policy_hints"].get(i).and_then(Value::as_str) {
            s.push_str(&format!("-- {h}\n"));
        }
        s.push_str(&format!(
            "CREATE TABLE {} (\n",
            r["name"].as_str().unwrap_or("")
        ));
        let cols: Vec<String> = r["columns"]
            .as_array()
            .into_iter()
            .flatten()
            .map(|col| {
                let t = match col["type"].as_str().unwrap_or("") {
                    "int" => "BIGINT",
                    "float" => "DOUBLE",
                    "bool" => "BOOLEAN",
                    "timestamp" => "TIMESTAMPTZ",
                    "date" => "DATE",
                    "bytes" => "BYTEA",
                    _ => "TEXT",
                };
                let mut line = format!("  {} {t}", col["name"].as_str().unwrap_or(""));
                if col["nullable"] == Value::Bool(false) {
                    line.push_str(" NOT NULL");
                }
                if let Some(e) = col["enum"].as_array() {
                    line.push_str(&format!(
                        " -- one of {}",
                        e.iter()
                            .filter_map(Value::as_str)
                            .collect::<Vec<_>>()
                            .join(", ")
                    ));
                }
                line
            })
            .collect();
        s.push_str(&cols.join(",\n"));
        s.push_str("\n);\n\n");
    }
    s
}
